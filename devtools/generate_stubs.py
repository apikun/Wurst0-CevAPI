#!/usr/bin/env python3
"""Generate Wurst0 stub hacks + Hacks.java from the original Wurst7-CevAPI source.

Reads original repo hacks/ folder, extracts class name / display name /
category, and generates Java 8 stub classes for every hack that has not
been ported yet. Fully ported hacks are skipped (handwritten files exist).
"""
import os
import re

ORIG = "/home/z/my-project/modport/original/src/main/java/net/wurstclient/hacks"
OUT = "/home/z/my-project/modport/fork/src/main/java/net/wurst0/hacks"

IMPLEMENTED = {
    "FlightHack", "SpeedHackHack", "AutoSprintHack", "StepHack",
    "NoFallHack", "TimerHack", "FullbrightHack", "PlayerEspHack",
    "MobEspHack", "ChestEspHack", "NameTagsHack", "XRayHack", "NukerHack",
    "FastPlaceHack", "AutoToolHack",
}

VALID_CATS = {
    "FAVORITES", "BLOCKS", "MOVEMENT", "COMBAT", "RENDER", "INTEL",
    "TOOLS", "CHAT", "FUN", "ITEMS", "OTHER", "CREATIVE_OP",
}

NAME_RE = re.compile(r'super\(\s*"((?:[^"\\]|\\.)*)"')
CAT_RE = re.compile(r'setCategory\(\s*Category\.(\w+)\s*\)')

HEADER = """/*
 * Wurst0 - a 1.12.2 port of Wurst7-CevAPI
 * Based on Wurst7 by Alexander01998 (GPL-3.0-or-later)
 * TODO: port logic from net/wurstclient/hacks/%s in the original
 * repo (MC 26.3 / Fabric). This stub only registers the hack so it
 * appears in the GUI; it currently does nothing when enabled.
 */
"""

hacks = []  # (class_name, display_name, category)

for fname in sorted(os.listdir(ORIG)):
    if not fname.endswith(".java"):
        continue
    cls = fname[:-5]
    with open(os.path.join(ORIG, fname), encoding="utf-8") as f:
        src = f.read()
    m = NAME_RE.search(src)
    display = m.group(1) if m else cls
    c = CAT_RE.search(src)
    cat = c.group(1) if c else "OTHER"
    if cat not in VALID_CATS:
        cat = "OTHER"
    hacks.append((cls, display, cat))

hacks.sort(key=lambda h: (h[2], h[1].lower()))

stub_count = 0
for cls, display, cat in hacks:
    if cls in IMPLEMENTED:
        continue
    path = os.path.join(OUT, cls + ".java")
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER % (cls + ".java"))
        f.write("package net.wurst0.hacks;\n\n")
        f.write("import net.wurst0.Category;\n")
        f.write("import net.wurst0.feature.Hack;\n\n")
        f.write("public final class %s extends Hack\n{\n" % cls)
        f.write("\tpublic %s()\n\t{\n" % cls)
        f.write('\t\tsuper("%s", "[not ported yet]");\n' % display)
        f.write("\t\tsetCategory(Category.%s);\n" % cat)
        f.write("\t}\n}\n")
    stub_count += 1

# generate Hacks.java
with open(os.path.join(OUT, "Hacks.java"), "w", encoding="utf-8") as f:
    f.write("/*\n * Wurst0 - a 1.12.2 port of Wurst7-CevAPI\n"
            " * Based on Wurst7 by Alexander01998 (GPL-3.0-or-later)\n"
            " * AUTO-GENERATED by scripts/generate_stubs.py - do not edit\n"
            " * the registration list by hand; edit the script instead.\n */\n")
    f.write("package net.wurst0.hacks;\n\n")
    f.write("import java.util.ArrayList;\n")
    f.write("import java.util.Collections;\n")
    f.write("import java.util.List;\n\n")
    f.write("import net.wurst0.feature.Hack;\n\n")
    f.write("public final class Hacks\n{\n")
    f.write("\tprivate final List<Hack> hacksList =\n"
            "\t\tnew ArrayList<Hack>();\n\n")
    f.write("\tpublic Hacks()\n\t{\n")
    for cls, display, cat in hacks:
        f.write("\t\tadd(new %s());\n" % cls)
    f.write("\t}\n\n")
    f.write("\tprivate void add(Hack hack)\n\t{\n"
            "\t\thacksList.add(hack);\n\t}\n\n")
    f.write("\tpublic List<Hack> getList()\n\t{\n"
            "\t\treturn Collections.unmodifiableList(hacksList);\n\t}\n\n")
    f.write("\tpublic Hack getByName(String name)\n\t{\n"
            "\t\tfor(Hack hack : hacksList)\n"
            "\t\t\tif(hack.getName().equalsIgnoreCase(name))\n"
            "\t\t\t\treturn hack;\n"
            "\t\treturn null;\n\t}\n}\n")

print("total original hacks:", len(hacks))
print("implemented:", len(IMPLEMENTED & {h[0] for h in hacks}))
print("stubs generated:", stub_count)
print("missing implemented:",
      IMPLEMENTED - {h[0] for h in hacks} or "none")
